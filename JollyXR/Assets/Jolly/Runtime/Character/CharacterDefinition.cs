using System;
using UnityEngine;

namespace Jolly.Character
{
    /// <summary>
    /// Everything that makes one character: the model and its animator, how the canonical face channels map onto its
    /// blendshapes or jaw, the look-at bones, its body size and its tuning. The runtime knows a character only through
    /// this asset, so adding one is adding an asset (docs/characters.md, ADR-0026). Field defaults are the Blender
    /// contract Nubi defines (docs/art/nubi/build_report.json); each asset holds its own values.
    /// </summary>
    [CreateAssetMenu(menuName = "Jolly/Character Definition", fileName = "Character")]
    public sealed class CharacterDefinition : ScriptableObject
    {
        [Header("Identity")]
        [Tooltip("Selection key for persistentDataPath/character.txt and build.sh --character: a-z, 0-9, '-' and '_'.")]
        public string id = "";
        [Tooltip("The name the character calls itself: persona prompts, greetings and canned lines say it where their " +
                 "text has {name}.")]
        public string displayName = "";
        [Tooltip("Optional UI string-table key of the name in other languages; empty or missing uses the display name.")]
        public string nameKey = "";
        [Tooltip("Words live ASR hears instead of the name, rewritten to the name before captions and the model " +
                 "(whole word, any case).")]
        public string[] aliases = Array.Empty<string>();

        [Header("Voice")]
        [Tooltip("The Wit voice it speaks with (ADR-0031); personas only scale it. Required: a character without one " +
                 "is not used, rather than speaking in another character's voice.")]
        public VoiceProfile voice;
        [Tooltip("Baked canned lines in this character's voice, per language. Lines that say the name play only these " +
                 "(Jolly/Character/Bake Named Lines For Selected Definition); other lines fall back to JollyConfig.lineClips.")]
        public LineClipSet[] lineClips = Array.Empty<LineClipSet>();

        [Header("Model")]
        [Tooltip("FBX or prefab instantiated under the character root: Generic rig, bones kept as GameObjects.")]
        public GameObject model;
        [Tooltip("States named after CharacterClips; generated by Jolly/Character/Build Animator For Selected Definition.")]
        public RuntimeAnimatorController animatorController;
        [Tooltip("Null keeps the avatar the model import created.")]
        public Avatar avatar;
        [Tooltip("Canonical clip name → clip. A canonical clip without an entry uses the model take of that name. " +
                 "Read by the animator builder and the validator only.")]
        public ClipBinding[] clips = Array.Empty<ClipBinding>();
        [Tooltip("Per-clip face weights by canonical clip and channel names (<Model>_FacePresets.json).")]
        public TextAsset facePresets;

        [Header("Face")]
        [Tooltip("SkinnedMeshRenderer holding the face blendshapes; empty picks the first one that has any.")]
        public string faceMesh = "";
        [Tooltip("One entry per canonical channel (FaceChannels.ShapeNames).")]
        public FaceChannelBinding[] face = FaceChannelBinding.Identity();
        public JawBinding jaw = new();

        [Header("Rig")]
        public RigBoneNames bones = new();

        [Header("Body (metres, in the character root's space)")]
        [Tooltip("Uniform scale of the model instance.")]
        public float scale = 1f;
        [Tooltip("NavMeshAgent and collider height.")]
        public float height = 0.9f;
        public float agentRadius = 0.22f;
        public float colliderRadius = 0.3f;
        [Tooltip("Half-extents of the contact shadow on the floor: x across the body, y front to back.")]
        public Vector2 contactShadowRadius = new(0.31f, 0.28f);

        [Header("Tuning")]
        [Tooltip("Walk speed, clip ground speeds, look limits and face timing.")]
        public NubiCharacterSettings tuning = new();

        /// <summary>The checks the runtime can afford before instantiating; the editor validator checks the rest.</summary>
        public bool IsUsable(out string reason)
        {
            reason = string.IsNullOrWhiteSpace(id) ? "no id"
                : voice == null ? "no voice"
                : model == null ? "no model"
                : animatorController == null ? "no animator controller"
                : facePresets == null ? "no face presets"
                : face == null ? "no face bindings"
                : bones == null ? "no rig bone names"
                : tuning == null ? "no tuning"
                : null;
            return reason == null;
        }

        void Reset() => face = FaceChannelBinding.Identity();
    }
}
